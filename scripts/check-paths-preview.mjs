import { chromium } from '@playwright/test';
import fs from 'node:fs';
const base=process.env.PATHS_PREVIEW_URL || 'http://127.0.0.1:3220';
if(!['http://127.0.0.1:3220','http://127.0.0.1:5174'].includes(base))throw new Error('只验证隔离试用地址');
const password=fs.readFileSync('.preview/access.txt','utf8').match(/密码：(.*)/)[1].trim();
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
const login=await context.request.post(`${base}/api/login`,{data:{username:'admin',password}});if(!login.ok())throw new Error(`login ${login.status()}`);
if(!(login.headers()['set-cookie']||'').includes('pm_paths_3220='))throw new Error('Cookie 未隔离');
const session=await (await context.request.get(`${base}/api/session`)).json();
const projects=await (await context.request.get(`${base}/api/projects`)).json();
const project=projects.find(p=>p.name==='交付依赖试用');
await context.addInitScript(({account,id})=>{const key=`project-manage:selected-project:${account}`;if(!localStorage.getItem(key))localStorage.setItem(key,id);},{account:session.accountId,id:project.id});
const page=await context.newPage(),errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
const apiOrigins=new Set();page.on('request',request=>{const url=new URL(request.url());if(url.pathname.startsWith('/api/'))apiOrigins.add(url.origin);});
fs.mkdirSync('.preview/qa',{recursive:true});
await page.goto(`${base}/paths`);await page.locator('[data-layout-ready="true"]').waitFor({timeout:30000});
await page.screenshot({path:'.preview/qa/global.png',fullPage:true});
const analysis=await (await context.request.get(`${base}/api/projects/${project.id}/path-analysis`)).json();
const estimateNode=analysis.nodes.find(n=>n.kind==='work'&&!['completed','cancelled'].includes(n.status));
const preview=await context.request.post(`${base}/api/projects/${project.id}/dependency-changes/preview`,{data:{expectedRevision:analysis.revision,target:'project',changes:{add:[],remove:[],estimates:[{workItemId:estimateNode.id,durationDays:estimateNode.estimate.durationDays||1}]}}});
if(!preview.ok()||!(await preview.json()).previewToken)throw new Error('批量预览接口未就绪');
if((await (await context.request.get(`${base}/api/projects/${project.id}/path-analysis`)).json()).revision!==analysis.revision)throw new Error('预览改变了正式版本');
const templates=await (await context.request.get(`${base}/api/templates?projectId=${project.id}`)).json();
await page.goto(`${base}/templates?edit=${(templates.find(t=>t.dependencyMode==='dependencies')||templates[0]).id}`);await page.locator('[data-layout-ready="true"]').waitFor({timeout:30000});
await page.screenshot({path:'.preview/qa/template-canvas.png',fullPage:true});
const req=analysis.requirements.find(r=>r.title==='订单业务上线');
const selected=analysis.nodes.find(n=>n.kind==='work'&&n.requirementId===req.id);
await page.goto(`${base}/requirements/${req.id}?view=path&target=project&pathNode=${selected.id}`);await page.locator('[data-layout-ready="true"]').waitFor({timeout:30000});
await page.screenshot({path:'.preview/qa/requirement.png',fullPage:true});
await page.setViewportSize({width:390,height:844});await page.waitForFunction(()=>document.querySelector('.dependency-canvas')?.getAttribute('data-layout-ready')==='true');
await page.screenshot({path:'.preview/qa/narrow.png',fullPage:true});
await page.setViewportSize({width:1440,height:1000});
const exceptions=projects.find(p=>p.name==='路径异常试用');
await page.evaluate(({account,id})=>localStorage.setItem(`project-manage:selected-project:${account}`,id),{account:session.accountId,id:exceptions.id});
await page.goto(`${base}/paths?pathScope=all`);await page.locator('[data-layout-ready="true"]').waitFor({timeout:30000});
await page.getByText('路径异常试用 · 项目交付',{exact:true}).waitFor();
await page.screenshot({path:'.preview/qa/exceptions.png',fullPage:true});
if([...apiOrigins].some(origin=>origin!==base))throw new Error('页面请求离开隔离服务');
const result={base,projectId:project.id,forecast:analysis.forecastEnd,cookie:'pm_paths_3220',batchPreview:true,templateCanvas:true,apiOrigins:[...apiOrigins],errors};
fs.writeFileSync(`.preview/qa/smoke-${new URL(base).port}.json`,JSON.stringify(result,null,2));
console.log(JSON.stringify(result));
await browser.close();
if(errors.length)process.exitCode=1;
