import {test,expect} from '@playwright/test';
import type {Requirement} from '../../src/client/types';
import {graphFixture} from './graph-fixture';
import {openGraph,graphToolbar,graphProperties} from './graph-interactions';
import {chooseOption} from './select-helper';

test('图中交接保留负责人、协作人和变更说明，刷新后可继续执行',async({page})=>{
  const {project,a}=await graphFixture(page,false);
  const read=async()=>(await(await page.request.get('/api/requirements/'+a.id)).json()) as Requirement;
  const people=await(await page.request.get('/api/people?projectId='+project.id)).json() as Array<{id:string;name:string}>;
  const original=people.find(person=>person.id===a.ownerId)!;
  const receiver=await(await page.request.post('/api/people',{data:{projectId:project.id,name:'图中接手人'+Date.now()}})).json() as {id:string;name:string};
  let work=(await read()).workItems[0];
  let response=await page.request.patch('/api/work-items/'+work.id,{data:{expectedVersion:work.version,ownerId:original.id}});expect(response.ok(),await response.text()).toBe(true);
  work=(await read()).workItems[0];
  response=await page.request.post('/api/work-items/'+work.id+'/start',{data:{expectedVersion:work.version}});expect(response.ok(),await response.text()).toBe(true);
  work=(await read()).workItems[0];
  response=await page.request.post('/api/requirements/'+a.id+'/progress',{data:{expectedVersion:work.version,workItemId:work.id,workItemPercent:40,content:'交接前完成初步联调'}});expect(response.ok(),await response.text()).toBe(true);
  const before=await read();work=before.workItems[0];
  await openGraph(page,'/requirements/'+a.id+'?view=path');
  await expect(page.locator('[data-layout-ready="true"]')).toBeVisible();
  await graphToolbar(page,'编辑画布');
  await graphProperties(page,page.locator('.react-flow__node[data-id="'+work.id+'"] .dependency-card'));
  await page.getByText('多人执行与变更说明',{exact:true}).click();
  await chooseOption(page.getByLabel('元素负责人',{exact:true}),receiver.id);
  await expect(page.getByRole('checkbox',{name:original.name,exact:true})).not.toBeChecked();
  const reason='交接字段核对，原负责人保留协作并解释接口边界。';
  await page.getByLabel('变更说明',{exact:true}).fill(reason);
  await page.getByRole('checkbox',{name:original.name,exact:true}).click();
  await expect(page.getByRole('checkbox',{name:original.name,exact:true})).toBeChecked();
  await graphToolbar(page,'保存修改');
  await expect(page.getByLabel('编辑画布',{exact:true})).toBeVisible();
  const saved=await read(),after=saved.workItems.find(row=>row.id===work.id)!;
  expect(after.ownerId).toBe(receiver.id);expect(after.collaborators.map(person=>person.id)).toEqual([original.id]);
  expect(after).toMatchObject({progress:40,status:'in_progress',plannedStart:work.plannedStart,plannedEnd:work.plannedEnd,actualStart:work.actualStart});
  expect(saved.progressUpdates?.filter(row=>row.content===reason)).toHaveLength(1);
  await page.reload();await expect(page.locator('[data-layout-ready="true"]')).toBeVisible();
  await page.getByRole('button',{name:work.title,exact:true}).click();
  await expect(page.getByRole('tabpanel',{name:'概况'})).toContainText(original.name);
  await page.getByRole('tab',{name:'记录',exact:true}).click();await expect(page.getByRole('tabpanel',{name:'记录'})).toContainText(reason);
});
