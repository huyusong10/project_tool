import {test,expect} from '@playwright/test';
import type {Requirement} from '../../src/client/types';
import {addBusinessDays,todayIso} from '../../src/shared/domain';
import {graphFixture} from './graph-fixture';
import {openGraph,graphToolbar,graphProperties} from './graph-interactions';

test('复制需求后从缺失计划提示进入依赖排期，原方案与历史保持',async({page})=>{
  const {project,a}=await graphFixture(page,false);
  const read=async(id:string)=>(await(await page.request.get('/api/requirements/'+id)).json()) as Requirement;
  const before=await read(a.id);
  await openGraph(page,'/paths?pathScope=all');
  await expect(page.locator('[data-layout-ready="true"]')).toBeVisible();
  await graphToolbar(page,'编辑画布');
  await graphProperties(page,page.locator('.react-flow__node[data-id="'+a.id+'"] .dependency-card'));
  await page.getByLabel('复制元素',{exact:true}).click();
  await graphToolbar(page,'保存修改');
  await expect(page.getByLabel('编辑画布',{exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:a.title+' 副本',exact:true})).toHaveCount(1);
  await page.getByRole('button',{name:a.title+' 副本',exact:true}).click();
  const copyId=new URL(page.url()).searchParams.get('detailId')!;
  const copied=await read(copyId);
  expect(copied).toMatchObject({status:'not_started',progress:0,plannedStart:null,plannedEnd:null});
  expect(copied.workItems).toHaveLength(before.workItems.length);
  expect(copied.workItems.map(work=>work.title)).toEqual(before.workItems.map(work=>work.title));
  expect(copied.workItems.every(work=>work.progress===0&&work.actualStart===null&&work.plannedStart===null)).toBe(true);
  await page.getByRole('button',{name:'调整计划',exact:true}).click();
  const form=page.getByRole('dialog',{name:'调整需求计划',exact:true});
  await expect(form).toContainText('缺少原计划开始日期');
  await form.getByLabel('计划开始',{exact:true}).fill(addBusinessDays(todayIso(),5));
  await expect(form.getByRole('button',{name:'保存排期',exact:true})).toBeDisabled();
  await page.setViewportSize({width:390,height:844});
  const entry=form.getByRole('button',{name:'按依赖预览排期',exact:true});
  await expect(entry).toBeVisible();
  expect(await form.evaluate(element=>element.scrollWidth<=element.clientWidth+1)).toBe(true);
  await entry.click();
  await expect(form).toHaveCount(0);
  await expect(page.getByRole('heading',{name:'交付排期预览',exact:true})).toBeVisible();
  await page.getByRole('button',{name:'预览并应用计划日期',exact:true}).click();
  const plan=page.getByRole('dialog',{name:'按依赖预览排期',exact:true}),start=addBusinessDays(todayIso(),5);
  await plan.getByLabel('需求开始锚点',{exact:true}).fill(start);
  await plan.getByRole('button',{name:'生成差异预览',exact:true}).click();
  await expect(plan.getByRole('row').filter({hasText:'方案交付'})).toContainText(start);
  await plan.getByRole('button',{name:'应用以上计划',exact:true}).click();
  await expect(plan).toHaveCount(0);
  const saved=await read(copyId);
  const source=saved.workItems.find(work=>work.title==='方案交付')!,target=saved.workItems.find(work=>work.title==='集成验证')!;
  expect(saved.plannedStart).toBe(start);
  expect(target.plannedStart!>source.plannedEnd!).toBe(true);
  expect(saved.workItems.every(work=>work.status==='not_started'&&work.progress===0)).toBe(true);
  const original=await read(a.id);
  expect(original).toMatchObject({id:before.id,title:before.title,version:before.version,ownerId:before.ownerId,status:before.status,progress:before.progress,plannedStart:before.plannedStart,plannedEnd:before.plannedEnd,actualStart:before.actualStart,actualEnd:before.actualEnd,progressUpdates:before.progressUpdates,referenceLinks:before.referenceLinks});
  expect(original.workItems).toEqual(before.workItems.map(work=>expect.objectContaining({id:work.id,title:work.title,version:work.version,ownerId:work.ownerId,collaborators:work.collaborators,status:work.status,progress:work.progress,plannedStart:work.plannedStart,plannedEnd:work.plannedEnd,actualStart:work.actualStart,actualEnd:work.actualEnd,referenceLinks:work.referenceLinks})));
  await page.reload();
  await expect(page.getByRole('heading',{name:'交付排期预览',exact:true})).toBeVisible();
  const graph=await(await page.request.get('/api/projects/'+project.id+'/path-graph?view=requirement&requirementId='+copyId)).json();
  expect(graph.analysis.dependencies.some((edge:{sourceWorkItemId:string;targetWorkItemId:string})=>edge.sourceWorkItemId===source.id&&edge.targetWorkItemId===target.id)).toBe(true);
});
