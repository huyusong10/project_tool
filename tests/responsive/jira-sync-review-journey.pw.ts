import { expect, test } from '@playwright/test';
import type { Requirement } from '../../src/client/types';
import { addBusinessDays, todayIso } from '../../src/shared/domain';
import { chooseOption, selectedValue } from './select-helper';

test('同步记录排除后刷新和需求历史往返保留范围，恢复只改变同步标记', async ({ page }) => {
  const post = async (url: string, data: object) => {
    const response = await page.request.post(url, { data });
    expect(response.ok(), await response.text()).toBe(true);
    return response.json();
  };
  await post('/api/login', { username: 'admin', password: '41_xc7q0qOjo4Inw!' });
  const project = await post('/api/projects', { name: '同步记录核对 ' + Date.now() });
  const owner = await post('/api/people', { projectId: project.id, name: '同步核对执行人 ' + Date.now() });
  const detail = async (id: string) => await (await page.request.get('/api/requirements/' + id)).json() as Requirement;
  const requirements: Requirement[] = [];
  for (const title of ['本次交付核对', '其他交付']) {
    let requirement = await post('/api/requirements', { projectId: project.id, ownerId: owner.id, title }) as Requirement;
    await post('/api/requirements/' + requirement.id + '/work-items', { expectedVersion: requirement.version, title: '整理材料', ownerId: owner.id, plannedStart: addBusinessDays(todayIso(), 0), plannedEnd: addBusinessDays(todayIso(), 1) });
    requirement = await detail(requirement.id);
    await post('/api/work-items/' + requirement.workItems[0].id + '/start', { expectedVersion: requirement.workItems[0].version });
    requirement = await detail(requirement.id);
    await post('/api/work-items/' + requirement.workItems[0].id + '/complete', { expectedVersion: requirement.workItems[0].version, content: '交付材料已完成并归档。' });
    requirements.push(await detail(requirement.id));
  }
  const [target, other] = requirements;
  const original = await detail(target.id), originalOther = await detail(other.id);
  const source = original.progressUpdates!.find(item => item.eventType === 'complete')!;
  await page.goto('/jira/prs?' + new URLSearchParams({ projectId: project.id, view: 'history' }));
  await page.getByRole('button', { name: '进展同步记录', exact: true }).click();
  const feature = page.getByRole('combobox', { name: '同步记录 Feature', exact: true });
  const phase = page.getByRole('combobox', { name: '同步记录 Phase', exact: true });
  const requirement = page.getByRole('combobox', { name: '同步记录需求', exact: true });
  const state = page.getByRole('combobox', { name: '进展同步状态', exact: true });
  const search = page.getByRole('searchbox', { name: '搜索同步记录', exact: true });
  const cutoff = page.getByLabel('同步记录截止日期', { exact: true });
  const pagination = page.getByRole('navigation', { name: '进展同步记录分页' });
  await chooseOption(feature, target.featureId!);
  await chooseOption(phase, '未归属 Phase');
  await chooseOption(requirement, target.id);
  await search.fill('交付材料');
  await cutoff.fill(todayIso());
  await expect(pagination).toContainText('共 1 条');
  await page.getByRole('checkbox', { name: '选择进展 ' + source.id, exact: true }).check();
  await page.getByRole('button', { name: '不再同步', exact: true }).click();
  await expect(pagination).toContainText('共 0 条');
  await chooseOption(state, 'ignored');
  await expect(pagination).toContainText('共 1 条');
  await page.reload();
  await expect(page.getByRole('button', { name: '进展同步记录', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await expect(pagination).toContainText('共 1 条');
  await expect(selectedValue(feature)).toHaveValue(target.featureId!);
  await expect(selectedValue(phase)).toHaveValue('未归属 Phase');
  await expect(selectedValue(requirement)).toHaveValue(target.id);
  await expect(selectedValue(state)).toHaveValue('ignored');
  await expect(search).toHaveValue('交付材料');
  await expect(cutoff).toHaveValue(todayIso());
  const reviewUrl = page.url();
  await page.getByRole('link', { name: target.title, exact: true }).click();
  const history = page.getByRole('tabpanel', { name: '记录', exact: true });
  await expect(history).toContainText('交付材料已完成并归档。');
  await expect(history).toContainText('不再同步');
  await page.goBack();
  await expect(page).toHaveURL(reviewUrl);
  await expect(pagination).toContainText('共 1 条');
  await page.getByRole('checkbox', { name: '选择进展 ' + source.id, exact: true }).check();
  await page.getByRole('button', { name: '恢复待同步', exact: true }).click();
  await expect(pagination).toContainText('共 0 条');
  await chooseOption(state, '');
  await page.reload();
  await expect(selectedValue(state)).toHaveValue('');
  await expect(pagination).toContainText('共 1 条');
  expect(await detail(target.id)).toEqual(original);
  expect(await detail(other.id)).toEqual(originalOther);
  await chooseOption(feature, '');
  await expect(selectedValue(phase)).toHaveValue('');
  await expect(selectedValue(requirement)).toHaveValue('');
  await expect(pagination).toContainText('共 2 条');
});
