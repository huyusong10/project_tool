import {expect,test} from '@playwright/test';
import type {Issue} from '../../src/client/types';

test.use({actionTimeout:10_000});
test('问题资料重读保留本地影响说明和其他人的字段修改',async({page})=>{
  const post=async(url:string,data:object)=>{const response=await page.request.post(url,{data});expect(response.ok(),await response.text()).toBe(true);return response.json();};
  const login=await post('/api/login',{username:'admin',password:'41_xc7q0qOjo4Inw!'});
  const project=await post('/api/projects',{name:'问题资料冲突 '+Date.now()});
  const owner=await post('/api/people',{projectId:project.id,name:'资料负责人 '+Date.now()});
  const replacement=await post('/api/people',{projectId:project.id,name:'最新负责人 '+Date.now()});
  let issue:Issue=await post('/api/issues',{projectId:project.id,title:'原问题标题',impact:'原影响说明',ownerId:owner.id,sourceRef:'OLD-1',reporter:owner.name,priority:'P2',discoveredAt:'2026-09-01',dueDate:'2026-10-01',nextReviewAt:'2026-09-25'});
  await post('/api/issues/'+issue.id+'/updates',{expectedVersion:issue.version,progress:42,content:'已有处理事实'});
  const endpoint='/api/issues/'+issue.id;
  const read=async()=>await(await page.request.get(endpoint)).json() as Issue;
  issue=await read();
  await page.addInitScript(({accountId,projectId})=>localStorage.setItem('project-manage:selected-project:'+accountId,projectId),{accountId:login.accountId,projectId:project.id});
  const url='/issues?issueId='+issue.id;
  let writes=0;page.on('request',request=>{if(request.method()==='PATCH'&&new URL(request.url()).pathname===endpoint)writes++;});
  await page.goto(url);await page.getByRole('tab',{name:'基本信息',exact:true}).click();
  const form=page.locator('.issue-form');
  await form.getByRole('textbox',{name:'问题影响',exact:true}).fill('本地补充影响说明');
  const remote={title:'另一处修订标题',ownerId:replacement.id,sourceRef:'NEW-2',reporter:replacement.name,priority:'P1',discoveredAt:'2026-09-02',dueDate:'2026-10-02',nextReviewAt:'2026-09-26'};
  const patch=await page.request.patch(endpoint,{data:{...remote,expectedVersion:issue.version}});expect(patch.ok(),await patch.text()).toBe(true);
  let latest=await read();
  const response=page.waitForResponse(r=>new URL(r.url()).pathname===endpoint&&r.request().method()==='PATCH');
  await form.getByRole('button',{name:'保存修改',exact:true}).click();expect((await response).status()).toBe(409);
  await expect(form).toContainText('已读取最新问题');
  expect(await read()).toEqual(latest);
  await expect.soft(form.getByRole('textbox',{name:'问题标题',exact:true})).toHaveValue(remote.title);
  await expect(form.getByRole('button',{name:'负责人：'+replacement.name,exact:true})).toBeVisible();
  await expect(form.locator('[name=dueDate]')).toHaveValue(remote.dueDate);
  await expect(form.locator('[name=priority]')).toHaveValue(remote.priority);
  await expect(form.getByRole('textbox',{name:'问题影响',exact:true})).toHaveValue('本地补充影响说明');
  await page.goto('/issues');await page.reload();await page.goto(url);await page.getByRole('tab',{name:'基本信息',exact:true}).click();
  await expect(form.getByRole('textbox',{name:'问题标题',exact:true})).toHaveValue(remote.title);
  const second={title:'再次确认的问题标题',impact:'另一处的影响说明',ownerId:null,reporter:null,sourceRef:null,dueDate:null,nextReviewAt:null};
  const secondPatch=await page.request.patch(endpoint,{data:{...second,expectedVersion:latest.version}});expect(secondPatch.ok(),await secondPatch.text()).toBe(true);
  latest=await read();
  const conflict=page.waitForResponse(r=>new URL(r.url()).pathname===endpoint&&r.request().method()==='PATCH');
  await form.getByRole('button',{name:'保存修改',exact:true}).click();expect((await conflict).status()).toBe(409);
  await expect(form).toContainText('已读取最新问题');
  expect(await read()).toEqual(latest);
  await expect(form.getByRole('textbox',{name:'问题标题',exact:true})).toHaveValue(second.title);
  await expect(form.getByRole('button',{name:'负责人：未分配',exact:true})).toBeVisible();
  await expect(form.locator('[name=dueDate]')).toHaveValue('');
  await expect(form.getByRole('textbox',{name:'问题影响',exact:true})).toHaveValue('本地补充影响说明');
  await form.getByRole('button',{name:'保存修改',exact:true}).click();
  await expect.poll(async()=> (await read()).version).toBe(latest.version+1);
  const saved=await read();
  expect(saved).toMatchObject({...remote,...second,impact:'本地补充影响说明',status:latest.status,progress:42,resolvedAt:latest.resolvedAt});
  expect(saved.updates).toEqual(latest.updates);
  expect(writes).toBe(3);
});
