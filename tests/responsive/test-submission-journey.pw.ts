import { expect, test } from '@playwright/test';
import { phaseFixture } from './phase-fixture';
import { todayIso } from '../../src/shared/domain';
import type { Requirement } from '../../src/client/types';

test('提测后能在概况和历史确认日期与说明，测试进度及未完成状态保持', async ({ page }) => {
  const f = await phaseFixture(page);
  const before = await (await page.request.get('/api/requirements/' + f.testing.id)).json() as Requirement;
  const note = '版本已部署到测试环境。\n剩余异常响应场景仍在验证，不代表最终交付。';
  await page.goto('/requirements/' + before.id);
  const detail = page.locator('.modal-card-workspace[role=dialog]');
  await detail.getByRole('button', { name: '记录提测', exact: true }).click();
  const form = page.getByRole('dialog', { name: '记录提测', exact: true });
  await form.getByLabel('说明', { exact: true }).fill(note);
  await form.getByRole('button', { name: '保存提测记录', exact: true }).click();
  await expect(form).toHaveCount(0);
  const overview = detail.getByRole('region', { name: '需求概览', exact: true });
  await expect(overview).toContainText('本轮提测：' + todayIso());
  await expect(overview).toContainText('测试中');
  await expect(overview).toContainText('70%');
  await overview.getByRole('button', { name: '查看提测记录', exact: true }).click();
  await expect(detail.getByRole('tab', { name: '记录', exact: true })).toHaveAttribute('aria-selected', 'true');
  await expect(detail.getByRole('region', { name: '进展记录', exact: true })).toContainText(note);
  await page.reload();
  await expect(detail.getByRole('region', { name: '进展记录', exact: true })).toContainText('实际提测日期：' + todayIso());
  await expect(detail.getByRole('region', { name: '进展记录', exact: true })).toContainText(note);
  const after = await (await page.request.get('/api/requirements/' + before.id)).json() as Requirement;
  expect(after).toMatchObject({ progress: before.progress, status: before.status, plannedStart: before.plannedStart, plannedEnd: before.plannedEnd });
  const workSnapshot = (requirement: Requirement) => requirement.workItems.map(work => ({ ...work, deliveryForecast: work.deliveryForecast && { ...work.deliveryForecast, revision: 0 } }));
  expect(workSnapshot(after)).toEqual(workSnapshot(before));
  expect(after.progressUpdates).toHaveLength((before.progressUpdates || []).length + 1);
  expect(after.progressUpdates?.[0]).toMatchObject({ eventType: 'note', content: '实际提测日期：' + todayIso() + '；' + note, percent: before.progress });
  await page.setViewportSize({ width: 390, height: 844 });
  await detail.getByRole('tab', { name: '概况', exact: true }).click();
  await expect(overview.getByRole('button', { name: '查看提测记录', exact: true })).toBeVisible();
  expect(await detail.evaluate(el => el.scrollWidth <= el.clientWidth + 1)).toBe(true);
  await overview.getByRole('button', { name: '查看提测记录', exact: true }).click();
  await expect(detail.getByRole('region', { name: '进展记录', exact: true })).toContainText(note);
});
