import {expect,test} from '@playwright/test';
import {phaseFixture} from './phase-fixture';
import type {FeaturePhase} from '../../src/shared/feature-phases';
import type {Requirement} from '../../src/client/types';

test('Phase 冲突重读保留本地修改并更新未修改字段',async({page})=>{
  const f=await phaseFixture(page),phaseId=f.phases[1].id;
  const executionFacts=(r:Requirement)=>({status:r.status,progress:r.progress,actualStart:r.actualStart,actualEnd:r.actualEnd,version:r.version,progressUpdates:r.progressUpdates,workItems:r.workItems.map(w=>({...w,deliveryForecast:{...w.deliveryForecast,revision:undefined}}))});
  const requirements=[f.testing,f.direct];
  const before=await Promise.all(requirements.map(async r=>executionFacts(await(await page.request.get('/api/requirements/'+r.id)).json())));
  const endpoint=f.base+'/features/'+f.feature.id+'/phases';
  const read=async()=>((await(await page.request.get(f.base+'/feature-phases')).json()) as FeaturePhase[]).find(p=>p.id===phaseId)!;
  await page.goto('/?'+new URLSearchParams({projectId:f.projectId,workspaceView:'list',scopeType:'project',detailId:'phase:'+phaseId}));
  await page.getByRole('button',{name:'编辑 Phase',exact:true}).click();
  const edit=page.getByRole('dialog',{name:'编辑 Phase',exact:true});
  await edit.getByRole('textbox',{name:'关注说明',exact:true}).fill('本地填写：重点核对导入失败的提示');
  await edit.getByRole('textbox',{name:'变更原因',exact:true}).fill('补充本次关注事项');
  const original=await read();
  const remote=await page.request.post(endpoint,{data:{id:phaseId,expectedVersion:original.version,name:original.name+' 资料更新',scope:'另一处补充的新交付范围',targetDate:'2026-10-16',sortOrder:4,referenceLinks:[{title:'范围来源',url:'https://example.com/phase-scope'}],reason:'核对交付资料'}});
  expect(remote.ok(),await remote.text()).toBe(true);
  let latest=await read();
  const response=page.waitForResponse(r=>new URL(r.url()).pathname===endpoint&&r.request().method()==='POST');
  await edit.getByRole('button',{name:'编辑 Phase',exact:true}).click();
  expect((await response).status()).toBe(409);
  await expect(edit.getByRole('button',{name:'编辑 Phase',exact:true})).toBeDisabled();
  expect(await read()).toEqual(latest);
  await edit.getByRole('button',{name:'读取最新 Phase 并核对',exact:true}).click();
  await expect(edit.getByRole('textbox',{name:'交付范围',exact:true})).toHaveValue(latest.scope);
  await expect(edit.getByRole('textbox',{name:'关注说明',exact:true})).toHaveValue('本地填写：重点核对导入失败的提示');
  await expect(edit.getByLabel('目标交付日期')).toHaveValue(latest.targetDate!);
  await expect(edit.getByLabel('展示顺序')).toHaveValue(String(latest.sortOrder+1));
  await expect(edit.getByRole('textbox',{name:'变更原因',exact:true})).toHaveValue('补充本次关注事项');
  await edit.getByRole('button',{name:'关闭',exact:true}).click();await page.reload();
  await page.getByRole('button',{name:'编辑 Phase',exact:true}).click();
  await expect(edit.getByRole('textbox',{name:'交付范围',exact:true})).toHaveValue(latest.scope);
  await expect(edit.getByRole('textbox',{name:'关注说明',exact:true})).toHaveValue('本地填写：重点核对导入失败的提示');
  const second=await page.request.post(endpoint,{data:{id:phaseId,expectedVersion:latest.version,name:latest.name,scope:'另一处再次确认的范围',note:'另一处修改的关注事项',targetDate:null,referenceLinks:[],reason:'第二次资料核对'}});
  expect(second.ok(),await second.text()).toBe(true);latest=await read();
  await edit.getByRole('button',{name:'编辑 Phase',exact:true}).click();
  await expect(edit.getByRole('button',{name:'编辑 Phase',exact:true})).toBeDisabled();expect(await read()).toEqual(latest);
  await edit.getByRole('button',{name:'读取最新 Phase 并核对',exact:true}).click();
  await expect(edit.getByRole('textbox',{name:'交付范围',exact:true})).toHaveValue(latest.scope);
  await expect(edit.getByLabel('目标交付日期')).toHaveValue('');
  await expect(edit.getByRole('textbox',{name:'关注说明',exact:true})).toHaveValue('本地填写：重点核对导入失败的提示');
  await edit.getByRole('button',{name:'编辑 Phase',exact:true}).click();await expect(edit).toHaveCount(0);
  const saved=await read();
  expect(saved).toMatchObject({name:latest.name,scope:latest.scope,targetDate:latest.targetDate,sortOrder:latest.sortOrder,referenceLinks:latest.referenceLinks,note:'本地填写：重点核对导入失败的提示'});
  expect(saved.requirements).toEqual(latest.requirements);
  expect(saved.version).toBe(latest.version+1);
  expect(await Promise.all(requirements.map(async r=>executionFacts(await(await page.request.get('/api/requirements/'+r.id)).json())))).toEqual(before);
});
